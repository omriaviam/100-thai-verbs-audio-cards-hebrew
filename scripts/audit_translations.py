def thai_key(value: str) -> str:
    value = unicodedata.normalize("NFC", value)
    return re.sub(r"[^\u0e00-\u0e7f]", "", value)


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit("usage: audit_translations.py EXTRACTED DRAFT OUTPUT")
    extracted_path, draft_path, output_path = map(Path, sys.argv[1:])
    extracted = json.loads(extracted_path.read_text(encoding="utf-8"))
    draft = json.loads(draft_path.read_text(encoding="utf-8"))
    prior = {thai_key(item["thai"]): item["hebrew"] for item in draft["items"]}

    applied = 0
    added = 0
    for item in extracted["items"]:
        hebrew = prior.get(thai_key(item["thai"]))
        if hebrew is None:
            hebrew = NEW_TRANSLATIONS.get(item["english"])
            if hebrew is None:
                raise ValueError(f"Missing Hebrew draft for {item['english']!r}")
            added += 1
        override = PAGE_OVERRIDES.get(
            (item["category"], item["sourcePage"], item["english"])
        )
        if override is None:
            override = OVERRIDES.get((item["category"], item["english"]))
        if override is not None:
            hebrew = override
            applied += 1
        item["hebrew"] = hebrew

    keys = [thai_key(item["thai"]) for item in extracted["items"]]
    if len(keys) != len(set(keys)):
        raise ValueError("Duplicate Thai remained after the audited merge")
    if any(not item.get("hebrew", "").strip() for item in extracted["items"]):
        raise ValueError("At least one audited item has no Hebrew translation")

    extracted["metadata"]["translationAudit"] = {
        "categoryAwareOverrides": applied,
        "newSplitEntriesTranslated": added,
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(extracted, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(
        json.dumps(
            {
                "items": len(extracted["items"]),
                "overridesApplied": applied,
                "newSplitEntriesTranslated": added,
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
